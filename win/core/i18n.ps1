function Get-Msg {
    param(
        [string]$Key,
        [string]$P1 = $null
    )
    $text = $global:Msg[$Key]
    if ($null -ne $P1 -and $text -match '\{0\}') {
        $text = $text -f $P1
    }
    return $text
}